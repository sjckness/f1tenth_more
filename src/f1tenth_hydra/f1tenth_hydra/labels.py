"""Isaac GT class ids -> Hydra labels (semantic_label_remap_filepath)."""

import os

import yaml

from f1tenth_hydra.camera import config_dir, load_yaml


def load_label_map(path=None):
    return load_yaml(path or os.path.join(config_dir(), 'labels', 'isaac_to_ade20k_mp3d.yaml'))


def isaac_semantics(scene_file=None, label_map=None):
    """class name -> Isaac id: the scene file's `semantics:` block, or the default table."""
    if scene_file:
        sem = load_yaml(os.path.expanduser(scene_file)).get('semantics')
        if not sem:
            raise ValueError(f'{scene_file}: no `semantics:` block')
        return {str(k): int(v) for k, v in sem.items()}
    label_map = label_map or load_label_map()
    return {str(k): int(v) for k, v in label_map['default_isaac_semantics'].items()}


def remap_pairs(semantics, label_map):
    """[{sub_id, super_id}] for Hydra, and the Isaac classes that have no Hydra label."""
    classes = label_map['classes']
    pairs, missing = [], []
    for name, isaac_id in sorted(semantics.items(), key=lambda kv: kv[1]):
        if name in classes:
            pairs.append({'sub_id': int(isaac_id), 'super_id': int(classes[name])})
        else:
            missing.append(name)
    return pairs, missing


def write_remap(out_path, scene_file=None, label_map_path=None):
    """Write Hydra's remap file; return (path, missing class names)."""
    label_map = load_label_map(label_map_path)
    pairs, missing = remap_pairs(isaac_semantics(scene_file, label_map), label_map)
    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('# generated by f1tenth_hydra.labels.write_remap\n')
        yaml.safe_dump(pairs, f, default_flow_style=None, sort_keys=False)
    return out_path, missing
