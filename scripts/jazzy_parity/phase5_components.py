#!/usr/bin/env python3
"""
Write the components.yaml a harness bring-up runs with.

Derived at run time from the INSTALLED production f1tenth_bringup/config/components.yaml of the
sourced workspace (so it cannot drift from it, on either side).

Runs on: the Orin host (native Humble: reads the native install's file),
inside the harness container (the image's file), linus. Called by
phase5_bringup.sh; prints what it changed relative to production.

  --empty NAME ...        keep component NAME registered but with no launch
                          files (component_supervisor_node indexes the
                          registry by every auto-started name, so removing
                          the key would crash it at startup). The bag-fed
                          harness empties hardware and perception: nothing
                          opens a serial port, a camera or the lidar.
  --drop-launch FILE ...  remove these launch files from whatever component
                          lists them
  --logger-runs-dir DIR   pass mission_logger_runs_dir:=DIR to
                          mission_logger.launch.py, so harness missions are
                          recorded under the run directory, never into the
                          car's archive (~/f1tenth_archive) that the archive
                          timer syncs to linus

A `health:` / `unwatched:` section (the old jazzy line's topic watchdog,
fix batch 5) is followed if the file has one: a check on a launch file that
was removed goes with it. main-jazzy's and the car's files have none.

Usage: phase5_components.py OUT.yaml [--empty ...] [--drop-launch ...]
                            [--logger-runs-dir DIR] [--source FILE]
"""
import argparse
import os
import sys

import yaml


def installed_components():
    from ament_index_python.packages import get_package_share_directory
    return os.path.join(get_package_share_directory('f1tenth_bringup'), 'config',
                        'components.yaml')


def derive(reg, empty=(), drop_launch=(), logger_runs_dir=None):
    """Apply the harness changes to a parsed registry; returns the change list."""
    comps = reg['components']
    changes = []
    for name in empty:
        if name not in comps:
            raise SystemExit('unknown component %s (have: %s)' % (name, ', '.join(comps)))
        changes.append('%s: emptied (was %s)' % (name, [e['launch_file'] for e in comps[name]]))
        comps[name] = []
    for name, entries in comps.items():
        kept = [e for e in entries if e['launch_file'] not in drop_launch]
        for e in entries:
            if e not in kept:
                changes.append('%s: dropped %s' % (name, e['launch_file']))
        comps[name] = kept
    health = reg.get('health') or {}
    for name in list(health):
        lfs = [e['launch_file'] for e in comps.get(name, [])]
        checks = health[name].get('checks', [])
        kept = [c for c in checks
                if c.get('launch_file', lfs[0] if len(lfs) == 1 else None) in lfs]
        if len(kept) != len(checks):
            changes.append('health.%s: dropped %d check(s) on launch files no longer '
                           'registered' % (name, len(checks) - len(kept)))
        if kept:
            health[name]['checks'] = kept
        else:
            del health[name]
            reg.setdefault('unwatched', {})[name] = 'no launch files in this harness run'
    if logger_runs_dir:
        found = False
        for entries in comps.values():
            for e in entries:
                if e['launch_file'] == 'mission_logger.launch.py':
                    e.setdefault('args', {})['mission_logger_runs_dir'] = logger_runs_dir
                    found = True
        if not found:
            raise SystemExit('no mission_logger.launch.py entry to redirect')
        changes.append('mission_logger.launch.py: mission_logger_runs_dir:=%s' % logger_runs_dir)
    return changes


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.strip().split('\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog=__doc__[__doc__.index('  --empty'):])
    ap.add_argument('out')
    ap.add_argument('--empty', nargs='*', default=[])
    ap.add_argument('--drop-launch', nargs='*', default=[])
    ap.add_argument('--logger-runs-dir')
    ap.add_argument('--source', help='components.yaml to start from (default: the installed one)')
    a = ap.parse_args(argv)
    src = a.source or installed_components()
    with open(src) as f:
        reg = yaml.safe_load(f)
    changes = derive(reg, a.empty, a.drop_launch, a.logger_runs_dir)
    with open(a.out, 'w') as f:
        f.write('# Generated by scripts/jazzy_parity/phase5_components.py from %s\n' % src)
        for c in changes:
            f.write('#   %s\n' % c)
        yaml.safe_dump(reg, f, sort_keys=False)
    print('\n'.join(changes) if changes else 'no changes (production registry)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
